create table if not exists public.shopee_custom_label_mappings (
  id bigint generated by default as identity primary key,
  product_name_key text not null,
  option_name_key text not null,
  product_name_display text not null default '',
  option_name_display text not null default '',
  bundle jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_name_key, option_name_key)
);

alter table public.shopee_custom_label_mappings enable row level security;
revoke all on table public.shopee_custom_label_mappings from anon, authenticated;
