insert into public.inventory_product_categories
  (source_key, source_id, name, sort_order, status, source_hash, source_payload)
select
  'product_category:' || allocated.source_id::text,
  allocated.source_id,
  allocated.category, 1000, 'active', '', jsonb_build_object('name', allocated.category)
from (
  select nextval('public.inventory_source_id_seq') as source_id, categories.category
  from (select distinct trim(category) as category from public.inventory_products where trim(category) <> '') categories
) allocated
where not exists (select 1 from public.inventory_product_categories c where c.name = allocated.category);

