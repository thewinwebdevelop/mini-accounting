create or replace function public.reverse_inventory_purchase_in(p_request jsonb, p_reversal_source_ids jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reference_type text := p_request->>'referenceType';
  v_reference_no text := p_request->>'referenceNo';
  v_cancellation text := p_request->>'cancellationReference';
  v_reversal_date date := (p_request->>'reversalDate')::date;
  v_expected bigint[];
  v_actual bigint[];
  v_original public.inventory_stock_movements%rowtype;
  v_relation public.inventory_stock_movement_reversals%rowtype;
  v_reverse public.inventory_stock_movements%rowtype;
  v_sku record;
  v_needed integer;
  v_available integer;
  v_sequence integer;
  v_reverse_id bigint;
  v_created timestamptz := coalesce((p_request->>'now')::timestamptz, now());
  v_reversals jsonb := '[]'::jsonb;
  v_unreversed integer := 0;
  v_has_original boolean := false;
begin
  if v_reference_type <> 'substitute_receipt'
    or v_reference_no !~ '^SR-[0-9]{4}-(0[1-9]|1[0-2])-[0-9]{4}$'
    or v_cancellation !~ '^workflow_transaction:TXN-[0-9]{4}-(0[1-9]|1[0-2])-[0-9]{4}$'
    or v_reversal_date is null
    or jsonb_typeof(p_request->'expectedOriginalMovementIds') <> 'array'
    or jsonb_typeof(p_reversal_source_ids) <> 'object' then
    return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID');
  end if;
  select array_agg(item::bigint order by item::bigint) into v_expected
  from jsonb_array_elements_text(p_request->'expectedOriginalMovementIds') as entries(item);
  if v_expected is null then v_expected := '{}'; end if;
  if cardinality(v_expected) <> (select count(distinct x) from unnest(v_expected) x) then
    return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID');
  end if;

  perform 1 from public.inventory_stock_movements
  where reference_type = v_reference_type and reference_no = v_reference_no
  order by source_id for update;
  select array_agg(source_id order by source_id) into v_actual
  from public.inventory_stock_movements
  where reference_type = v_reference_type and reference_no = v_reference_no;
  v_has_original := v_actual is not null and cardinality(v_actual) > 0;
  if not v_has_original then
    if cardinality(v_expected) > 0 then return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID'); end if;
    return jsonb_build_object('status', 'not_required', 'referenceType', v_reference_type, 'referenceNo', v_reference_no, 'reversals', '[]'::jsonb);
  end if;
  if v_actual is distinct from v_expected or exists (
    select 1 from public.inventory_stock_movements
    where reference_type = v_reference_type and reference_no = v_reference_no and movement_type <> 'purchase_in'
  ) then
    return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID');
  end if;

  perform 1 from public.inventory_stock_skus s
  where s.source_id in (
    select distinct stock_sku_source_id from public.inventory_stock_movements
    where source_id = any(v_expected)
  ) order by s.source_id for update;

  -- Validate any prior reversals and compute stock needs before inserting rows.
  for v_original in select * from public.inventory_stock_movements where source_id = any(v_expected) order by source_id loop
    select * into v_relation from public.inventory_stock_movement_reversals
    where original_movement_source_id = v_original.source_id;
    if found then
      select * into v_reverse from public.inventory_stock_movements where source_id = v_relation.reversal_movement_source_id;
      if not found or v_relation.cancellation_reference <> v_cancellation
        or v_reverse.movement_type <> 'adjustment_out'
        or v_reverse.stock_sku_source_id <> v_original.stock_sku_source_id
        or v_reverse.quantity <> v_original.quantity
        or v_reverse.unit_cost <> v_original.unit_cost
        or v_reverse.total_cost <> v_original.total_cost
        or v_reverse.movement_date <> v_reversal_date
        or v_reverse.reference_type <> 'workflow_cancellation'
        or v_reverse.reference_no <> v_cancellation then
        return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID');
      end if;
    else
      v_unreversed := v_unreversed + 1;
      select coalesce(sum(case when movement_type in ('purchase_in','return_in','adjustment_in') then quantity when movement_type in ('sale_out','adjustment_out') then -quantity else 0 end),0)::integer
      into v_available from public.inventory_stock_movements where stock_sku_source_id = v_original.stock_sku_source_id;
      select coalesce(sum(quantity),0)::integer into v_needed from public.inventory_stock_movements m
      where m.source_id = any(v_expected) and m.stock_sku_source_id = v_original.stock_sku_source_id
        and not exists (select 1 from public.inventory_stock_movement_reversals r where r.original_movement_source_id=m.source_id);
      if v_available < v_needed then
        return jsonb_build_object('error', 'INSUFFICIENT_STOCK_FOR_CANCELLATION', 'sku', v_original.stock_sku_source_id, 'availableQuantity', v_available, 'requiredQuantity', v_needed);
      end if;
    end if;
  end loop;

  -- Prevent cross-receipt reuse of a parent cancellation reference with malformed rows.
  if exists (
    select 1 from public.inventory_stock_movements r
    left join public.inventory_stock_movement_reversals rel on rel.reversal_movement_source_id = r.source_id
    left join public.inventory_stock_movements original on original.source_id = rel.original_movement_source_id
    where r.reference_type = 'workflow_cancellation' and r.reference_no = v_cancellation
      and (rel.original_movement_source_id is null or original.movement_type <> 'purchase_in'
        or rel.cancellation_reference <> v_cancellation or r.movement_type <> 'adjustment_out'
        or r.stock_sku_source_id <> original.stock_sku_source_id or r.quantity <> original.quantity
        or r.unit_cost <> original.unit_cost or r.total_cost <> original.total_cost or r.movement_date <> v_reversal_date)
  ) then return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID'); end if;

  for v_original in select * from public.inventory_stock_movements where source_id = any(v_expected) order by source_id loop
    select * into v_relation from public.inventory_stock_movement_reversals where original_movement_source_id = v_original.source_id;
    if found then v_reverse_id := v_relation.reversal_movement_source_id;
    else
      v_reverse_id := (p_reversal_source_ids->>v_original.source_id::text)::bigint;
      if v_reverse_id is null or v_reverse_id <= 0 then return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID'); end if;
      insert into public.inventory_movement_sequences (movement_date, next_sequence) values (v_reversal_date, 2)
      on conflict (movement_date) do update set next_sequence = public.inventory_movement_sequences.next_sequence + 1
      returning next_sequence - 1 into v_sequence;
      insert into public.inventory_stock_movements (
        source_key, source_id, stock_sku_source_id, movement_no, movement_type, movement_date,
        quantity, unit_cost, total_cost, reference_type, reference_no, note, created_at, source_hash, source_payload
      ) values (
        'stock_movement:' || v_reverse_id::text, v_reverse_id, v_original.stock_sku_source_id,
        'MOV-' || to_char(v_reversal_date, 'YYYYMMDD') || '-' || lpad(v_sequence::text, 5, '0'),
        'adjustment_out', v_reversal_date, v_original.quantity, v_original.unit_cost, v_original.total_cost,
        'workflow_cancellation', v_cancellation, 'Workflow cancellation stock reversal', v_created, '', '{}'
      ) returning * into v_reverse;
      insert into public.inventory_stock_movement_reversals (original_movement_source_id, reversal_movement_source_id, cancellation_reference, created_at)
      values (v_original.source_id, v_reverse_id, v_cancellation, v_created);
    end if;
    select * into v_reverse from public.inventory_stock_movements where source_id = v_reverse_id;
    v_reversals := v_reversals || jsonb_build_array(jsonb_build_object(
      'originalMovementId', v_original.source_id, 'reversalMovementId', v_reverse.source_id,
      'movementNo', v_reverse.movement_no, 'movementDate', v_reverse.movement_date,
      'stockSkuId', v_original.stock_sku_source_id, 'quantity', v_original.quantity
    ));
  end loop;
  return jsonb_build_object(
    'status', case when v_unreversed > 0 then 'reversed' else 'already_reversed' end,
    'referenceType', v_reference_type, 'referenceNo', v_reference_no, 'reversals', v_reversals
  );
exception when unique_violation then
  return jsonb_build_object('error', 'STOCK_REVERSAL_SOURCE_INVALID');
end
$$;

revoke all on function public.reverse_inventory_purchase_in(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.reverse_inventory_purchase_in(jsonb, jsonb) to service_role;

create or replace function public.replace_inventory_reservations(p_order_line_key text, p_reference_no text, p_reservations jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item jsonb;
  v_stock_id bigint;
  v_quantity integer;
  v_id bigint;
  v_balance integer;
  v_reserved integer;
  v_rows jsonb := '[]'::jsonb;
begin
  if p_order_line_key is null or trim(p_order_line_key) = '' or jsonb_typeof(p_reservations) is distinct from 'array' then
    return jsonb_build_object('error', 'INVALID_RESERVATIONS');
  end if;
  if exists (select 1 from jsonb_array_elements(p_reservations) as entries(item)
    where item->>'stockSkuId' is null or (item->>'stockSkuId') !~ '^[1-9][0-9]*$'
      or item->>'quantity' is null or (item->>'quantity') !~ '^[1-9][0-9]*$') then
    return jsonb_build_object('error', 'INVALID_RESERVATIONS');
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_reservations) as entries(item)
    group by (item->>'stockSkuId')::bigint having count(*) > 1
  ) then return jsonb_build_object('error', 'INVALID_RESERVATIONS'); end if;
  perform 1 from public.inventory_stock_skus s where s.source_id in
    (select (item->>'stockSkuId')::bigint from jsonb_array_elements(p_reservations) as entries(item)) order by s.source_id for update;
  if exists (
    select 1 from jsonb_array_elements(p_reservations) as entries(item)
    where not exists (select 1 from public.inventory_stock_skus s where s.source_id=(item->>'stockSkuId')::bigint)
  ) then return jsonb_build_object('error', 'STOCK_SKU_NOT_FOUND'); end if;
  for v_stock_id, v_quantity in
    select (item->>'stockSkuId')::bigint, sum((item->>'quantity')::integer)::integer
    from jsonb_array_elements(p_reservations) as entries(item)
    group by (item->>'stockSkuId')::bigint
  loop
    select coalesce(sum(case when movement_type in ('purchase_in','return_in','adjustment_in') then quantity
      when movement_type in ('sale_out','adjustment_out') then -quantity else 0 end),0)::integer
      into v_balance from public.inventory_stock_movements where stock_sku_source_id=v_stock_id;
    select coalesce(sum(quantity),0)::integer into v_reserved from public.inventory_stock_reservations
      where stock_sku_source_id=v_stock_id and status='reserved' and order_line_key<>p_order_line_key;
    if v_balance-v_reserved < v_quantity then
      return jsonb_build_object('error','INSUFFICIENT_STOCK','stockSkuId',v_stock_id,
        'availableQuantity',v_balance-v_reserved,'requiredQuantity',v_quantity);
    end if;
  end loop;
  update public.inventory_stock_reservations r set status='released', updated_at=now()
  where r.order_line_key=p_order_line_key and r.status='reserved'
    and not exists (select 1 from jsonb_array_elements(p_reservations) as entries(item)
      where (item->>'stockSkuId')::bigint=r.stock_sku_source_id);
  for v_item in select item from jsonb_array_elements(p_reservations) as entries(item) loop
    v_stock_id := (v_item->>'stockSkuId')::bigint;
    v_quantity := (v_item->>'quantity')::integer;
    v_id := nextval('public.inventory_source_id_seq');
    insert into public.inventory_stock_reservations (
      source_key, source_id, stock_sku_source_id, order_line_key, quantity, status, reference_no, source_payload
    ) values (
      'inventory_reservation:' || p_order_line_key || ':' || v_stock_id::text, v_id, v_stock_id,
      p_order_line_key, v_quantity, 'reserved', coalesce(p_reference_no, ''), v_item
    ) on conflict (source_key) do update set quantity=excluded.quantity, status='reserved',
      reference_no=excluded.reference_no, updated_at=now(), source_hash=excluded.source_hash,
      source_payload=excluded.source_payload returning source_id into v_id;
    v_rows := v_rows || jsonb_build_array(jsonb_build_object('sourceId', v_id, 'stockSkuId', v_stock_id, 'quantity', v_quantity));
  end loop;
  return jsonb_build_object('reservations', v_rows);
end
$$;

revoke all on function public.replace_inventory_reservations(text, text, jsonb) from public, anon, authenticated;
grant execute on function public.replace_inventory_reservations(text, text, jsonb) to service_role;

create or replace function public.set_inventory_reservation_status(p_order_line_key text, p_status text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare v_count integer;
begin
  if p_status not in ('released', 'fulfilled') then return -1; end if;
  update public.inventory_stock_reservations set status=p_status,updated_at=now()
  where order_line_key=p_order_line_key and status='reserved';
  get diagnostics v_count = row_count;
  return v_count;
end
$$;

