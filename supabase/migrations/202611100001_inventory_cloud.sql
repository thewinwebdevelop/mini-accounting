-- Durable inventory extensions used by Cloud Run. Keep IDs compatible with the
-- numeric source IDs used by inventory_products and inventory_stock_skus.
create sequence if not exists public.inventory_source_id_seq
  as bigint
  start with 8000000000000000
  increment by 1
  no minvalue
  no maxvalue
  cache 100;

create table if not exists public.inventory_product_categories (
  source_key text primary key,
  source_id bigint not null unique,
  name text not null unique,
  sort_order integer not null default 0 check (sort_order >= 0),
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  source_hash text not null default '',
  source_payload jsonb not null default '{}'::jsonb
);

