create or replace function public.validate_inventory_product_category()
returns trigger language plpgsql set search_path = public as $$
begin
  if not exists (select 1 from public.inventory_product_categories c where c.name = trim(new.category) and c.status = 'active') then
    raise exception using errcode = '23514', message = 'PRODUCT_CATEGORY_NOT_FOUND';
  end if;
  return new;
end
$$;

drop trigger if exists inventory_product_category_required on public.inventory_products;
create trigger inventory_product_category_required before insert or update of category on public.inventory_products
for each row execute function public.validate_inventory_product_category();

create or replace function public.validate_inventory_stock_sku_parent()
returns trigger language plpgsql set search_path = public as $$
begin
  if not exists (select 1 from public.inventory_products p where p.source_id = new.product_source_id and p.status = 'active') then
    raise exception using errcode = '23514', message = 'PRODUCT_NOT_FOUND';
  end if;
  return new;
end
$$;

