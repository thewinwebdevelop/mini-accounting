create or replace function public.save_inventory_sale_sku(p_sale_sku jsonb, p_components jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_source_key text := p_sale_sku->>'source_key';
  v_source_id bigint := (p_sale_sku->>'source_id')::bigint;
  v_sale_sku text := upper(trim(p_sale_sku->>'sale_sku'));
  v_display_name text := trim(p_sale_sku->>'display_name');
  v_component jsonb;
  v_stock_id bigint;
  v_seen bigint[] := '{}';
  v_row public.inventory_sale_skus%rowtype;
begin
  if v_source_id is null or v_source_key is null or v_source_key <> ('sale_sku:' || v_source_id::text)
    or v_sale_sku is null or v_sale_sku = '' or v_display_name is null or v_display_name = ''
    or jsonb_typeof(p_components) is distinct from 'array' then
    return jsonb_build_object('error', 'INVALID_SALE_SKU');
  end if;
  if jsonb_array_length(p_components) = 0 then
    return jsonb_build_object('error', 'SALE_SKU_COMPONENTS_REQUIRED');
  end if;
  for v_component in select value from jsonb_array_elements(p_components) loop
    begin
      v_stock_id := (v_component->>'stockSkuId')::bigint;
    exception when others then
      return jsonb_build_object('error', 'INVALID_SALE_SKU_COMPONENT');
    end;
    if v_stock_id is null or v_stock_id = any(v_seen)
      or v_component->>'quantity' is null or (v_component->>'quantity') !~ '^[1-9][0-9]*$'
      or not exists (
        select 1 from public.inventory_stock_skus s
        where s.source_id = v_stock_id and s.status = 'active'
      ) then
      return jsonb_build_object('error', 'INVALID_SALE_SKU_COMPONENT');
    end if;
    v_seen := array_append(v_seen, v_stock_id);
  end loop;

  insert into public.inventory_sale_skus (
    source_key, source_id, sale_sku, display_name, platform, platform_product_id,
    platform_variation_id, status, created_at, updated_at, source_hash, source_payload
  ) values (
    v_source_key, v_source_id, v_sale_sku, v_display_name,
    coalesce(nullif(p_sale_sku->>'platform', ''), 'manual'),
    coalesce(p_sale_sku->>'platform_product_id', ''),
    coalesce(p_sale_sku->>'platform_variation_id', ''),
    coalesce(nullif(p_sale_sku->>'status', ''), 'active'),
    coalesce((p_sale_sku->>'created_at')::timestamptz, now()),
    coalesce((p_sale_sku->>'updated_at')::timestamptz, now()),
    coalesce(p_sale_sku->>'source_hash', ''), coalesce(p_sale_sku->'source_payload', '{}'::jsonb)
  ) on conflict (source_key) do update set
    sale_sku = excluded.sale_sku,
    display_name = excluded.display_name,
    platform = excluded.platform,
    platform_product_id = excluded.platform_product_id,
    platform_variation_id = excluded.platform_variation_id,
    status = excluded.status,
    updated_at = excluded.updated_at,
    source_hash = excluded.source_hash,
    source_payload = excluded.source_payload
  returning * into v_row;

  delete from public.inventory_bundle_components where sale_sku_source_id = v_source_id;
  for v_component in select value from jsonb_array_elements(p_components) loop
    insert into public.inventory_bundle_components (sale_sku_source_id, stock_sku_source_id, quantity)
    values (v_source_id, (v_component->>'stockSkuId')::bigint, (v_component->>'quantity')::integer);
  end loop;
  return to_jsonb(v_row);
exception when unique_violation then
  return jsonb_build_object('error', 'SALE_SKU_ALREADY_EXISTS');
end
$$;

revoke all on function public.save_inventory_sale_sku(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.save_inventory_sale_sku(jsonb, jsonb) to service_role;

create or replace function public.create_inventory_purchase_in(p_record jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.inventory_stock_movements%rowtype;
  v_row public.inventory_stock_movements%rowtype;
  v_source_key text := p_record->>'source_key';
  v_source_id bigint := (p_record->>'source_id')::bigint;
  v_stock_id bigint := (p_record->>'stock_sku_source_id')::bigint;
  v_date date := (p_record->>'movement_date')::date;
  v_quantity integer := (p_record->>'quantity')::integer;
  v_unit_cost numeric(14,2) := (p_record->>'unit_cost')::numeric(14,2);
  v_idempotency_key text := nullif(p_record->>'idempotency_key', '');
  v_sequence integer;
begin
  if v_source_id is null or v_source_key is null or v_source_key <> ('stock_movement:' || v_source_id::text)
    or v_stock_id is null or v_date is null or v_quantity is null or v_quantity <= 0
    or v_unit_cost is null or v_unit_cost <= 0 then
    return jsonb_build_object('error', 'INVALID_PURCHASE_IN');
  end if;

  if v_idempotency_key is not null then
    select * into v_existing from public.inventory_stock_movements
    where idempotency_key = v_idempotency_key;
    if found then
      if v_existing.stock_sku_source_id <> v_stock_id
        or v_existing.movement_type <> 'purchase_in'
        or v_existing.movement_date <> v_date
        or v_existing.quantity <> v_quantity
        or v_existing.unit_cost <> v_unit_cost
        or v_existing.total_cost <> round(v_quantity * v_unit_cost, 2)
        or v_existing.reference_type <> coalesce(p_record->>'reference_type', 'manual')
        or v_existing.reference_no <> coalesce(p_record->>'reference_no', '')
        or v_existing.note <> coalesce(p_record->>'note', '') then
        return jsonb_build_object('error', 'IDEMPOTENCY_CONFLICT');
      end if;
      return to_jsonb(v_existing);
    end if;
  end if;

  perform 1 from public.inventory_stock_skus
  where source_id = v_stock_id and status = 'active' for update;
  if not found then return jsonb_build_object('error', 'STOCK_SKU_NOT_FOUND'); end if;

  insert into public.inventory_movement_sequences (movement_date, next_sequence)
  values (v_date, 2)
  on conflict (movement_date) do update
    set next_sequence = public.inventory_movement_sequences.next_sequence + 1
  returning next_sequence - 1 into v_sequence;

  insert into public.inventory_stock_movements (
    source_key, source_id, stock_sku_source_id, movement_no, movement_type,
    movement_date, quantity, unit_cost, total_cost, reference_type, reference_no,
    note, created_at, source_hash, source_payload, idempotency_key
  ) values (
    v_source_key, v_source_id, v_stock_id,
    'MOV-' || to_char(v_date, 'YYYYMMDD') || '-' || lpad(v_sequence::text, 5, '0'),
    'purchase_in', v_date, v_quantity, v_unit_cost, round(v_quantity * v_unit_cost, 2),
    coalesce(p_record->>'reference_type', 'manual'), coalesce(p_record->>'reference_no', ''),
    coalesce(p_record->>'note', ''), coalesce((p_record->>'created_at')::timestamptz, now()),
    coalesce(p_record->>'source_hash', ''), coalesce(p_record->'source_payload', '{}'::jsonb), v_idempotency_key
  ) returning * into v_row;
  return to_jsonb(v_row);
exception when unique_violation then
  if v_idempotency_key is not null then
    select * into v_existing from public.inventory_stock_movements where idempotency_key = v_idempotency_key;
    if found then
      if v_existing.stock_sku_source_id = v_stock_id and v_existing.movement_type = 'purchase_in'
        and v_existing.movement_date = v_date and v_existing.quantity = v_quantity
        and v_existing.unit_cost = v_unit_cost and v_existing.total_cost = round(v_quantity * v_unit_cost, 2)
        and v_existing.reference_type = coalesce(p_record->>'reference_type', 'manual')
        and v_existing.reference_no = coalesce(p_record->>'reference_no', '')
        and v_existing.note = coalesce(p_record->>'note', '') then
        return to_jsonb(v_existing);
      end if;
      return jsonb_build_object('error', 'IDEMPOTENCY_CONFLICT');
    end if;
  end if;
  return jsonb_build_object('error', 'MOVEMENT_ALREADY_EXISTS');
end
$$;

revoke all on function public.create_inventory_purchase_in(jsonb) from public, anon, authenticated;
grant execute on function public.create_inventory_purchase_in(jsonb) to service_role;

create or replace function public.apply_inventory_stock_movements(p_records jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_record jsonb;
  v_row public.inventory_stock_movements%rowtype;
  v_stock_id bigint;
  v_source_id bigint;
  v_source_key text;
  v_type text;
  v_date date;
  v_quantity integer;
  v_unit_cost numeric(14,2);
  v_idempotency_key text;
  v_sequence integer;
  v_balance integer;
  v_reserved integer;
  v_incoming integer;
  v_required integer;
  v_result jsonb := '[]'::jsonb;
begin
  if jsonb_typeof(p_records) <> 'array' or jsonb_array_length(p_records) = 0 then
    return jsonb_build_object('error', 'INVALID_STOCK_MOVEMENTS');
  end if;
  -- Validate all records and stable identities before locking or writing.
  for v_record in select item from jsonb_array_elements(p_records) as entries(item) loop
    begin
      v_source_id := (v_record->>'source_id')::bigint;
      v_stock_id := (v_record->>'stock_sku_source_id')::bigint;
      v_date := (v_record->>'movement_date')::date;
      v_quantity := (v_record->>'quantity')::integer;
      v_unit_cost := coalesce((v_record->>'unit_cost')::numeric(14,2), 0);
    exception when others then
      return jsonb_build_object('error', 'INVALID_STOCK_MOVEMENTS');
    end;
    v_source_key := v_record->>'source_key';
    v_type := v_record->>'movement_type';
    if v_source_id is null or v_source_key is distinct from ('stock_movement:' || v_source_id::text)
      or v_stock_id is null or v_date is null or v_quantity is null or v_quantity <= 0
      or v_unit_cost < 0 or v_type is null or v_type not in ('purchase_in','sale_out','return_in','adjustment_in','adjustment_out') then
      return jsonb_build_object('error', 'INVALID_STOCK_MOVEMENTS');
    end if;
  end loop;

  if exists (
    select 1 from jsonb_array_elements(p_records) as entries(item)
    group by item->>'source_key' having count(*) > 1
  ) or exists (
    select 1 from jsonb_array_elements(p_records) as entries(item)
    group by (item->>'source_id')::bigint having count(*) > 1
  ) then
    return jsonb_build_object('error','MOVEMENT_ALREADY_EXISTS');
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_records) as entries(item)
    where nullif(item->>'idempotency_key','') is not null
    group by item->>'idempotency_key' having count(*) > 1
  ) then
    return jsonb_build_object('error','IDEMPOTENCY_CONFLICT');
  end if;

  perform 1 from public.inventory_stock_skus s
  where s.source_id in (select distinct (item->>'stock_sku_source_id')::bigint from jsonb_array_elements(p_records) as entries(item))
  order by s.source_id for update;
  if exists (
    select 1 from jsonb_array_elements(p_records) as entries(item)
    where not exists (select 1 from public.inventory_stock_skus s where s.source_id=(item->>'stock_sku_source_id')::bigint)
  ) then return jsonb_build_object('error', 'STOCK_SKU_NOT_FOUND'); end if;

  -- An idempotency key only replays the same logical movement. Reusing it
  -- with changed stock, quantity, price, date, or reference is a conflict.
  for v_record in select item from jsonb_array_elements(p_records) as entries(item) loop
    v_idempotency_key := nullif(v_record->>'idempotency_key','');
    if v_idempotency_key is not null then
      select * into v_row from public.inventory_stock_movements where idempotency_key=v_idempotency_key;
    else
      select * into v_row from public.inventory_stock_movements where source_key=v_record->>'source_key';
    end if;
    if found and (
      v_row.stock_sku_source_id <> (v_record->>'stock_sku_source_id')::bigint
      or v_row.movement_type <> v_record->>'movement_type'
      or v_row.movement_date <> (v_record->>'movement_date')::date
      or v_row.quantity <> (v_record->>'quantity')::integer
      or v_row.unit_cost <> coalesce((v_record->>'unit_cost')::numeric(14,2),0)
      or v_row.total_cost <> coalesce((v_record->>'total_cost')::numeric(14,2),
        round((v_record->>'quantity')::numeric * coalesce((v_record->>'unit_cost')::numeric,0),2))
      or v_row.reference_type <> coalesce(v_record->>'reference_type','manual')
      or v_row.reference_no <> coalesce(v_record->>'reference_no','')
      or v_row.note <> coalesce(v_record->>'note','')
    ) then
      return jsonb_build_object('error', case when v_idempotency_key is null
        then 'MOVEMENT_ALREADY_EXISTS' else 'IDEMPOTENCY_CONFLICT' end);
    end if;
  end loop;

  -- Check total availability per SKU, including all records in this batch.
  for v_stock_id in select distinct (item->>'stock_sku_source_id')::bigint from jsonb_array_elements(p_records) as entries(item) loop
    select coalesce(sum(case when movement_type in ('purchase_in','return_in','adjustment_in') then quantity
      when movement_type in ('sale_out','adjustment_out') then -quantity else 0 end),0)::integer
      into v_balance from public.inventory_stock_movements where stock_sku_source_id=v_stock_id;
    select coalesce(sum(quantity),0)::integer into v_reserved from public.inventory_stock_reservations
      where stock_sku_source_id=v_stock_id and status='reserved';
    select coalesce(sum(case when item->>'movement_type' in ('purchase_in','return_in','adjustment_in')
      then (item->>'quantity')::integer else 0 end),0)::integer,
      coalesce(sum(case when item->>'movement_type' in ('sale_out','adjustment_out')
      then (item->>'quantity')::integer else 0 end),0)::integer
      into v_incoming, v_required
      from jsonb_array_elements(p_records) as entries(item)
      where (item->>'stock_sku_source_id')::bigint=v_stock_id
        and not exists (select 1 from public.inventory_stock_movements existing
          where existing.source_key=item->>'source_key'
             or (nullif(item->>'idempotency_key','') is not null and existing.idempotency_key=item->>'idempotency_key'));
    if v_balance - v_reserved + v_incoming < v_required then
      return jsonb_build_object('error','INSUFFICIENT_STOCK','stockSkuId',v_stock_id,
        'availableQuantity',v_balance-v_reserved+v_incoming,'requiredQuantity',v_required);
    end if;
  end loop;

  for v_record in select item from jsonb_array_elements(p_records) as entries(item) loop
    v_source_id := (v_record->>'source_id')::bigint;
    v_source_key := v_record->>'source_key';
    v_idempotency_key := nullif(v_record->>'idempotency_key','');
    if v_idempotency_key is not null then
      select * into v_row from public.inventory_stock_movements where idempotency_key=v_idempotency_key;
    else
      select * into v_row from public.inventory_stock_movements where source_key=v_source_key;
    end if;
    if found then
      v_result := v_result || jsonb_build_array(to_jsonb(v_row));
      continue;
    end if;
    v_stock_id := (v_record->>'stock_sku_source_id')::bigint;
    v_date := (v_record->>'movement_date')::date;
    v_quantity := (v_record->>'quantity')::integer;
    v_unit_cost := coalesce((v_record->>'unit_cost')::numeric(14,2),0);
    v_type := v_record->>'movement_type';
    insert into public.inventory_movement_sequences(movement_date,next_sequence) values(v_date,2)
    on conflict(movement_date) do update set next_sequence=public.inventory_movement_sequences.next_sequence+1
    returning next_sequence-1 into v_sequence;
    insert into public.inventory_stock_movements (
      source_key,source_id,stock_sku_source_id,movement_no,movement_type,movement_date,quantity,
      unit_cost,total_cost,reference_type,reference_no,note,created_at,source_hash,source_payload,idempotency_key
    ) values (
      v_source_key,v_source_id,v_stock_id,'MOV-'||to_char(v_date,'YYYYMMDD')||'-'||lpad(v_sequence::text,5,'0'),
      v_type,v_date,v_quantity,v_unit_cost,coalesce((v_record->>'total_cost')::numeric(14,2),round(v_quantity*v_unit_cost,2)),
      coalesce(v_record->>'reference_type','manual'),coalesce(v_record->>'reference_no',''),coalesce(v_record->>'note',''),
      coalesce((v_record->>'created_at')::timestamptz,now()),coalesce(v_record->>'source_hash',''),
      coalesce(v_record->'source_payload','{}'::jsonb),v_idempotency_key
    ) returning * into v_row;
    v_result := v_result || jsonb_build_array(to_jsonb(v_row));
  end loop;
  return v_result;
exception when unique_violation then
  return jsonb_build_object('error','MOVEMENT_ALREADY_EXISTS');
end
$$;

